"""Turn the latest learnings into a pull request a human can accept or reject. Never merges, never touches main.

  uv run propose.py                 # branch flywheel/<date>, regenerate report + PLAYBOOK, draft skill edits, open PR
  uv run propose.py --no-llm        # data-only PR (report + PLAYBOOK), skip Claude's prose edits
  uv run propose.py --no-pr         # stop after the commit; inspect locally

Claude (headless `claude -p`) may edit ONLY the files in EDITABLE; anything else it touches is reverted.
"""
import argparse
import datetime as dt
import re
import subprocess
import sys
from pathlib import Path

import learn

ROOT = learn.ROOT
EDITABLE = ["cold-email/copy-frameworks/SKILL.md", "cold-email/sequence-architecture/SKILL.md",
            "campaign-analytics/winning-copy-extraction/SKILL.md", "learnings/"]
GENERATED = ["cold-email/copy-frameworks/PLAYBOOK.md", "reports/"]
HUMAN_OWNED_HINT = ("Threshold tables ('Metrics That Matter', 'Define Winning Copy') are HUMAN-OWNED: you may propose "
                    "a new number only by adding a '<!-- proposed: ... (evidence: report row) -->' comment next to it.")


def git(*args, check=True):
    return subprocess.run(["git", *args], cwd=ROOT, text=True, capture_output=True, check=check).stdout.strip()


def changed_paths():
    return [l[3:] for l in git("status", "--porcelain").splitlines()]


def disallowed(paths, allowed=EDITABLE + GENERATED):
    return [p for p in paths if not any(p == a or (a.endswith("/") and p.startswith(a)) for a in allowed)]


def frontmatter_ok(path):
    text = (ROOT / path).read_text()
    return bool(re.match(r"^---\nname: .+\ndescription: .+\n---\n", text, re.S)) if path.endswith("SKILL.md") else True


def ask_claude(report_path, as_of):
    prompt = f"""You maintain the GTM Flywheel skills. Read {report_path} and cold-email/copy-frameworks/PLAYBOOK.md.
Then make the smallest edits to these files that the evidence supports: {', '.join(EDITABLE[:-1])}.
Rules: every changed line must be justified by a specific row in the report (cite it in a trailing HTML comment,
e.g. <!-- evidence: {as_of} archetype table, The Observation 6.1% vs 3.2%, P=0.94 -->). Do not reorder or rewrite
sections. Do not invent numbers. {HUMAN_OWNED_HINT}
Also append 3-5 bullets of qualitative takeaways to learnings/{as_of[:7]}.md under a '## {as_of}' heading
(create the file if missing). If the report shows no winners, change nothing except the learnings note."""
    r = subprocess.run(["claude", "-p", prompt, "--permission-mode", "acceptEdits", "--allowedTools", "Read,Edit,Write"],
                       cwd=ROOT, text=True, capture_output=True)
    if r.returncode:
        print("claude -p failed; continuing with data-only PR:\n" + r.stderr[-2000:], file=sys.stderr)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--as-of", default=dt.date.today().isoformat())
    ap.add_argument("--base", default="main")
    ap.add_argument("--no-llm", action="store_true")
    ap.add_argument("--no-pr", action="store_true")
    ap.add_argument("--by-persona", action="store_true")
    a = ap.parse_args(argv)

    if changed_paths():
        sys.exit("working tree is not clean; commit or stash first so the PR contains only flywheel changes")
    branch = f"flywheel/{a.as_of}"
    git("checkout", "-B", branch, a.base)
    (ROOT / "learnings").mkdir(exist_ok=True)

    learn.main(["--as-of", a.as_of] + (["--by-persona"] if a.by_persona else []))
    report = f"reports/{a.as_of}-copy-learnings.md"
    if not a.no_llm:
        ask_claude(report, a.as_of)

    bad = disallowed(changed_paths())
    if bad:
        print(f"reverting edits outside the allowlist: {bad}", file=sys.stderr)
        git("checkout", "--", *bad, check=False)
        for p in bad:
            if (ROOT / p).exists() and p not in git("ls-files").splitlines():
                (ROOT / p).unlink()
    broken = [p for p in changed_paths() if not frontmatter_ok(p)]
    if broken:
        git("checkout", "--", *broken)
        print(f"reverted {broken}: SKILL.md frontmatter would have broken", file=sys.stderr)

    if not changed_paths():
        sys.exit("nothing changed; no PR")
    git("add", "-A")
    git("commit", "-q", "-m", f"flywheel: copy learnings {a.as_of}\n\nGenerated by flywheel/propose.py. Review before merging.")
    print(f"committed on {branch}:\n" + git("show", "--stat", "--oneline", "HEAD"))
    if a.no_pr:
        return
    git("push", "-u", "origin", branch)
    body = (ROOT / report).read_text()
    url = subprocess.run(["gh", "pr", "create", "--base", a.base, "--head", branch,
                          "--title", f"Flywheel: copy learnings {a.as_of}",
                          "--body", f"Proposed by `flywheel/propose.py`. Nothing here is applied until you merge.\n\n{body}"],
                         cwd=ROOT, text=True, capture_output=True, check=True).stdout.strip()
    print(url)


if __name__ == "__main__":
    main()
